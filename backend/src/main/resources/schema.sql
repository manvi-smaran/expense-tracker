-- Expense Tracker schema (PostgreSQL; also runs on H2 in PostgreSQL mode).
-- Applied automatically at start-up; every statement is idempotent. Can also be pasted into Neon's SQL Editor.

CREATE TABLE IF NOT EXISTS users (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(300) NOT NULL);

CREATE TABLE IF NOT EXISTS tokens (
  token_hash CHAR(64) PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL);

CREATE TABLE IF NOT EXISTS categories (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(50) NOT NULL,
  color VARCHAR(9) NOT NULL,
  icon VARCHAR(20) NOT NULL,
  built_in BOOLEAN DEFAULT FALSE NOT NULL);

CREATE TABLE IF NOT EXISTS expenses (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  category_id INT REFERENCES categories(id) ON DELETE SET NULL,
  amount DECIMAL(12,2) NOT NULL,
  description VARCHAR(200) NOT NULL,
  expense_date DATE NOT NULL,
  note VARCHAR(500));

CREATE INDEX IF NOT EXISTS ix_expenses_user_date ON expenses(user_id, expense_date);

CREATE TABLE IF NOT EXISTS budgets (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  category_id INT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  limit_amount DECIMAL(12,2) NOT NULL,
  alert_threshold_percent INT NOT NULL,
  UNIQUE (user_id, category_id));

CREATE TABLE IF NOT EXISTS subscriptions (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  category_id INT REFERENCES categories(id) ON DELETE SET NULL,
  name VARCHAR(100) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  frequency VARCHAR(10) NOT NULL,
  next_due_date DATE NOT NULL,
  active BOOLEAN DEFAULT TRUE NOT NULL);
